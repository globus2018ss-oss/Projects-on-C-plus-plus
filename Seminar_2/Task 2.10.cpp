/*Задча 10
Условие:
Дан самолёт с возможностью изменения тяги двигателя (от Tmin до Tamx с шгом дельтаT)
Требуется:
Для каждого значения тяги вычислить вертикалное ускорение и врем набора заданной высоты h
Найти значение тяги, при котором, время набора высоты минимально
Вывести оптимальное значение тяги и соответствующее время*/

#include <iostream>
#include <cmath>
#include <clocale>

using namespace std;

int main() {

    setlocale(LC_ALL, "RUS");

    double Tmin, Tmax, dT;
    double m, L, D;
    double h;
    const double g = 9.81;

    cout << "Введите минимальную тягу Tmin: ";
    cin >> Tmin;
    cout << "Введите максимальную тягу Tmax: ";
    cin >> Tmax;
    cout << "Введите шаг dT: ";
    cin >> dT;

    cout << "Введите массу самолета m: ";
    cin >> m;
    cout << "Введите подъемную силу L: ";
    cin >> L;
    cout << "Введите сопротивление D: ";
    cin >> D;
    cout << "Введите заданную высоту h: ";
    cin >> h;

    double minTime = 1e9;
    double optimalT = Tmin;

    // Примечание: в рамках данной модели вертикальное ускорение ay = (L - mg)/m 
    // не зависит от тяги T. Если тяга влияет на скорость, а скорость на L, 
    // то модель должна быть сложнее. Здесь предполагаем, что L задана.
    // Если же требуется учитывать изменение L от T, это нужно уточнять в условии.

    for (double T = Tmin; T <= Tmax; T += dT) {
        // Вычисляем вертикальное ускорение (предполагая, что L и m постоянны)
        double ay = (L - m * g) / m;

        if (ay > 0) {
            double t = sqrt(2 * h / ay);
            if (t < minTime) {
                minTime = t;
                optimalT = T;
            }
        }
    }

    if (minTime == 1e9) {
        cout << "Невозможно набрать высоту ни при одном значении тяги (ay <= 0)" << endl;
    }
    else {
        cout << "Оптимальная тяга: " << optimalT << " Н" << endl;
        cout << "Минимальное время набора высоты: " << minTime << " с" << endl;
    }

    return 0;
}